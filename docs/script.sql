-- G01 — Quanto entrou, quanto saiu e quanto sobrou de cada fantasia no período?
-- Atende: P1 (controle de entrada e saída de fantasias)
SELECT f.ID_FANTASIA, f.NM_FANTASIA, f.TP_CATEGORIA,
       COALESCE(e.entradas, 0) AS entradas, COALESCE(s.saidas, 0) AS saidas, f.QT_DISPONIVEL
FROM FANTASIA f
LEFT JOIN (SELECT ID_FANTASIA, SUM(QT_ENTRADA) AS entradas FROM ENTRA GROUP BY ID_FANTASIA) e ON e.ID_FANTASIA = f.ID_FANTASIA
LEFT JOIN (SELECT ID_FANTASIA, SUM(QT_ITEM) AS saidas FROM CONTEM GROUP BY ID_FANTASIA) s ON s.ID_FANTASIA = f.ID_FANTASIA
ORDER BY saidas DESC;

-- G02 — Qual a taxa de divergência no recebimento de cada fornecedor (pedido x recebido)?
-- Atende: P1 (entradas) e KPI taxa de divergência no recebimento (RN09)
SELECT fo.NM_FORNECEDOR, COUNT(*) AS itens_recebidos, SUM(en.QT_SOLICITADA) AS pecas_pedidas, SUM(en.QT_ENTRADA) AS pecas_recebidas,
       SUM(CASE WHEN en.QT_ENTRADA < en.QT_SOLICITADA THEN 1 ELSE 0 END) AS itens_com_divergencia,
       ROUND(100.0 * (SUM(en.QT_SOLICITADA) - SUM(en.QT_ENTRADA)) / SUM(en.QT_SOLICITADA), 2) AS pct_pecas_faltantes
FROM ENTRA en
JOIN FANTASIA fa   ON fa.ID_FANTASIA = en.ID_FANTASIA
JOIN FORNECEDOR fo ON fo.ID_FORNECEDOR = fa.ID_FORNECEDOR
GROUP BY fo.ID_FORNECEDOR, fo.NM_FORNECEDOR
ORDER BY pct_pecas_faltantes DESC;

-- G03 — Quantas vendas, quantas peças, quanto faturamos e qual o ticket médio por mês?
-- Atende: P2 (controle de vendas) e KPI ticket médio
SELECT DATE_FORMAT(v.DT_VENDA, '%Y-%m') AS mes, COUNT(DISTINCT v.ID_VENDA) AS qt_vendas, SUM(c.QT_ITEM) AS qt_pecas,
       SUM(c.QT_ITEM * c.VL_PRATICADO) AS faturamento,
       ROUND(SUM(c.QT_ITEM * c.VL_PRATICADO) / COUNT(DISTINCT v.ID_VENDA), 2) AS ticket_medio
FROM VENDA v
JOIN CONTEM c ON c.ID_VENDA = v.ID_VENDA
GROUP BY DATE_FORMAT(v.DT_VENDA, '%Y-%m')
ORDER BY mes;

-- G04 — Quantas vendas por dia a loja faz em cada mês (a meta informada é de 10 a 15 por dia)?
-- Atende: P2 e KPI média de vendas por dia
SELECT mes, SUM(qt) AS vendas, COUNT(*) AS dias_com_venda, ROUND(SUM(qt) * 1.0 / COUNT(*), 1) AS media_vendas_por_dia,
       MIN(qt) AS minimo_dia, MAX(qt) AS maximo_dia
FROM (SELECT DATE_FORMAT(DT_VENDA, '%Y-%m') AS mes, DT_VENDA, COUNT(*) AS qt FROM VENDA GROUP BY DT_VENDA) d
GROUP BY mes
ORDER BY mes;

-- G05 — Quais são as 10 fantasias mais vendidas?
-- Atende: P2 e KPI fantasias mais vendidas (a loja hoje só "sente" a demanda)
SELECT * FROM (
  SELECT f.ID_FANTASIA, f.NM_FANTASIA, f.TP_CATEGORIA, SUM(c.QT_ITEM) AS pecas_vendidas,
         SUM(c.QT_ITEM * c.VL_PRATICADO) AS faturamento,
         RANK() OVER (ORDER BY SUM(c.QT_ITEM) DESC) AS posicao
  FROM FANTASIA f
  JOIN CONTEM c ON c.ID_FANTASIA = f.ID_FANTASIA
  GROUP BY f.ID_FANTASIA, f.NM_FANTASIA, f.TP_CATEGORIA
) r
WHERE posicao <= 10
ORDER BY posicao, NM_FANTASIA;

-- G06 — Quanto cada forma de pagamento representa no faturamento?
-- Atende: P2 (controle de vendas)
SELECT v.TP_FORMA_PAGAMENTO, COUNT(DISTINCT v.ID_VENDA) AS qt_vendas, SUM(c.QT_ITEM * c.VL_PRATICADO) AS valor,
       ROUND(100.0 * SUM(c.QT_ITEM * c.VL_PRATICADO) / (SELECT SUM(QT_ITEM * VL_PRATICADO) FROM CONTEM), 1) AS pct_do_faturamento
FROM VENDA v
JOIN CONTEM c ON c.ID_VENDA = v.ID_VENDA
GROUP BY v.TP_FORMA_PAGAMENTO
ORDER BY valor DESC;

-- G07 — Varejo x atacado: quantas vendas, peças, faturamento e ticket médio de cada tipo?
-- Atende: P2 e KPI faturamento por tipo de venda (RN01)
SELECT t.TP_VENDA, COUNT(*) AS qt_vendas, SUM(t.pecas) AS qt_pecas, SUM(t.total) AS faturamento, ROUND(AVG(t.total), 2) AS ticket_medio
FROM (SELECT v.ID_VENDA, v.TP_VENDA, SUM(c.QT_ITEM) AS pecas, SUM(c.QT_ITEM * c.VL_PRATICADO) AS total
      FROM VENDA v JOIN CONTEM c ON c.ID_VENDA = v.ID_VENDA GROUP BY v.ID_VENDA, v.TP_VENDA) t
GROUP BY t.TP_VENDA;

-- G08 — Como as vendas variam por categoria de fantasia a cada mês (sazonalidade)?
-- Atende: P2 e KPI vendas por categoria (RN12)
SELECT DATE_FORMAT(v.DT_VENDA, '%Y-%m') AS mes, f.TP_CATEGORIA, SUM(c.QT_ITEM) AS pecas, SUM(c.QT_ITEM * c.VL_PRATICADO) AS faturamento
FROM VENDA v
JOIN CONTEM c   ON c.ID_VENDA = v.ID_VENDA
JOIN FANTASIA f ON f.ID_FANTASIA = c.ID_FANTASIA
GROUP BY DATE_FORMAT(v.DT_VENDA, '%Y-%m'), f.TP_CATEGORIA
ORDER BY mes, faturamento DESC;

-- G09 — Qual o fluxo de caixa por dia (entradas, saídas, saldo do dia e saldo acumulado)?
-- Atende: P3 (fluxo de caixa) e KPI saldo de caixa (parte do saldo inicial do 1º fechamento)
SELECT dia, entradas, saidas, entradas - saidas AS saldo_do_dia,
       (SELECT VL_SALDO_INICIAL FROM FECHAMENTO_CAIXA ORDER BY DT_FECHAMENTO LIMIT 1) + SUM(entradas - saidas) OVER (ORDER BY dia) AS saldo_acumulado
FROM (SELECT DT_MOV AS dia,
             SUM(CASE WHEN TP_MOV = 'entrada' THEN VL_MOV ELSE 0 END) AS entradas,
             SUM(CASE WHEN TP_MOV = 'saida' THEN VL_MOV ELSE 0 END) AS saidas
      FROM CAIXA GROUP BY DT_MOV) d
ORDER BY dia;

-- G10 — Quais fechamentos de caixa tiveram diferença e qual o percentual de fechamentos com diferença?
-- Atende: P3 (fechamento de caixa) e KPI % de fechamentos com diferença (RN14)
SELECT fc.ID_FECHAMENTO, fc.DT_FECHAMENTO, fc.VL_SALDO_INICIAL, fc.VL_CONTADO, fc.VL_DIFERENCA,
       ROUND(100.0 * SUM(CASE WHEN fc.VL_DIFERENCA <> 0 THEN 1 ELSE 0 END) OVER () / COUNT(*) OVER (), 1) AS pct_fechamentos_com_diferenca
FROM FECHAMENTO_CAIXA fc
ORDER BY fc.DT_FECHAMENTO;

-- G11 — Quanto movimento de caixa ainda não foi conferido em nenhum fechamento?
-- Atende: P3 (fechamento de caixa)
SELECT TP_MOV, COUNT(*) AS movimentos, SUM(VL_MOV) AS valor, MIN(DT_MOV) AS desde, MAX(DT_MOV) AS ate
FROM CAIXA
WHERE ID_FECHAMENTO IS NULL
GROUP BY TP_MOV;

-- G12 — Quais fantasias estão na quantidade mínima ou abaixo e precisam de reposição?
-- Atende: P4 (quantidade disponível) e KPI fantasias abaixo do estoque mínimo (RN07)
SELECT f.ID_FANTASIA, f.NM_FANTASIA, f.TP_CATEGORIA, f.QT_DISPONIVEL, f.QT_MINIMA,
       CASE WHEN f.QT_DISPONIVEL = 0 THEN 'sem estoque' ELSE 'repor' END AS situacao,
       fo.NM_FORNECEDOR, fo.NR_TELEFONE
FROM FANTASIA f
JOIN FORNECEDOR fo ON fo.ID_FORNECEDOR = f.ID_FORNECEDOR
WHERE f.QT_DISPONIVEL <= f.QT_MINIMA
ORDER BY f.QT_DISPONIVEL, f.NM_FANTASIA;

-- G13 — Quantas peças há em estoque por categoria e quanto isso vale ao custo médio?
-- Atende: P4 (quantidade disponível)
SELECT f.TP_CATEGORIA, COUNT(*) AS modelos, SUM(f.QT_DISPONIVEL) AS pecas_em_estoque,
       ROUND(SUM(f.QT_DISPONIVEL * cm.custo_medio), 2) AS valor_ao_custo
FROM FANTASIA f
JOIN (SELECT ID_FANTASIA, SUM(VL_CUSTO * QT_ENTRADA) / SUM(QT_ENTRADA) AS custo_medio FROM ENTRA GROUP BY ID_FANTASIA) cm
  ON cm.ID_FANTASIA = f.ID_FANTASIA
GROUP BY f.TP_CATEGORIA
ORDER BY pecas_em_estoque DESC;

-- G14 — Qual a taxa de troca por mês (trocas em relação às vendas)?
-- Atende: P2 e KPI taxa de troca (RN04)
SELECT m.mes, m.vendas, COALESCE(t.trocas, 0) AS trocas,
       ROUND(100.0 * COALESCE(t.trocas, 0) / m.vendas, 2) AS taxa_troca_pct
FROM (SELECT DATE_FORMAT(DT_VENDA, '%Y-%m') AS mes, COUNT(*) AS vendas FROM VENDA GROUP BY DATE_FORMAT(DT_VENDA, '%Y-%m')) m
LEFT JOIN (SELECT DATE_FORMAT(DT_TROCA, '%Y-%m') AS mes, COUNT(*) AS trocas FROM TROCA GROUP BY DATE_FORMAT(DT_TROCA, '%Y-%m')) t
       ON t.mes = m.mes
ORDER BY m.mes;

-- G15 — Qual a margem bruta de cada fantasia (preço de varejo menos custo médio de compra)?
-- Atende: KPI margem bruta (RN10: preço definido a partir do custo)
SELECT f.ID_FANTASIA, f.NM_FANTASIA, f.TP_CATEGORIA, f.VL_VENDA_VAREJO, ROUND(cm.custo_medio, 2) AS custo_medio,
       ROUND(f.VL_VENDA_VAREJO - cm.custo_medio, 2) AS margem_unitaria,
       ROUND(100.0 * (f.VL_VENDA_VAREJO - cm.custo_medio) / f.VL_VENDA_VAREJO, 1) AS margem_pct
FROM FANTASIA f
JOIN (SELECT ID_FANTASIA, SUM(VL_CUSTO * QT_ENTRADA) / SUM(QT_ENTRADA) AS custo_medio FROM ENTRA GROUP BY ID_FANTASIA) cm
  ON cm.ID_FANTASIA = f.ID_FANTASIA
ORDER BY margem_pct DESC;

-- G16 — Que percentual das vendas é feito sem cadastro de cliente?
-- Atende: KPI % de vendas sem cadastro (RN05, RN06)
SELECT COUNT(*) AS total_vendas,
       SUM(CASE WHEN ID_CLIENTE = 1 THEN 1 ELSE 0 END) AS vendas_sem_cadastro,
       ROUND(100.0 * SUM(CASE WHEN ID_CLIENTE = 1 THEN 1 ELSE 0 END) / COUNT(*), 1) AS pct_sem_cadastro
FROM VENDA;

-- G17 — Quais clientes cadastrados nunca compraram?
-- Atende: KPI clientes cadastrados sem compras (apoio a campanhas de relacionamento)
SELECT c.ID_CLIENTE, c.NM_CLIENTE, c.IN_AUTORIZA_LGPD
FROM CLIENTE c
LEFT JOIN VENDA v ON v.ID_CLIENTE = c.ID_CLIENTE
WHERE v.ID_VENDA IS NULL AND c.ID_CLIENTE <> 1
ORDER BY c.ID_CLIENTE;

-- G18 — Quantas vendas foram entregues por cada meio e qual o valor médio delas?
-- Atende: KPI vendas com entrega (RN02: só a partir de R$ 200)
SELECT t.TP_ENTREGA, COUNT(*) AS qt_vendas, ROUND(AVG(t.total), 2) AS valor_medio, MIN(t.total) AS menor_valor
FROM (SELECT v.ID_VENDA, v.TP_ENTREGA, SUM(c.QT_ITEM * c.VL_PRATICADO) AS total
      FROM VENDA v JOIN CONTEM c ON c.ID_VENDA = v.ID_VENDA WHERE v.TP_ENTREGA IS NOT NULL GROUP BY v.ID_VENDA, v.TP_ENTREGA) t
GROUP BY t.TP_ENTREGA;

-- G19 — Quantas encomendas (fantasia pedida ao fornecedor para o cliente) foram vendidas e quanto valeram?
-- Atende: KPI encomendas (RN11)
SELECT COUNT(DISTINCT v.ID_VENDA) AS encomendas, SUM(c.QT_ITEM) AS pecas, SUM(c.QT_ITEM * c.VL_PRATICADO) AS valor
FROM VENDA v
JOIN CONTEM c ON c.ID_VENDA = v.ID_VENDA
WHERE v.IN_ENCOMENDA = 1;

-- ---------------------------------------------------------------------
-- 6. CONSULTAS DE AUDITORIA (A) — cada uma confere uma regra de negócio
--    (as que retornam linhas apontam inconsistências propositais da massa de dados)
-- ---------------------------------------------------------------------

-- A01 — Existe venda de atacado com menos de 6 peças ou venda de varejo com 6 peças ou mais?
-- Verifica: RN01 (atacado vale a partir de 6 peças)
SELECT v.ID_VENDA, v.DT_VENDA, v.TP_VENDA, SUM(c.QT_ITEM) AS pecas
FROM VENDA v
JOIN CONTEM c ON c.ID_VENDA = v.ID_VENDA
GROUP BY v.ID_VENDA, v.DT_VENDA, v.TP_VENDA
HAVING (v.TP_VENDA = 'atacado' AND SUM(c.QT_ITEM) < 6) OR (v.TP_VENDA = 'varejo' AND SUM(c.QT_ITEM) >= 6);

-- A02 — Existe item vendido por valor diferente do preço de tabela do tipo da venda?
-- Verifica: RN01 e RN10 (preço de varejo ou de atacado definido na FANTASIA)
SELECT c.ID_VENDA, v.TP_VENDA, f.NM_FANTASIA, c.VL_PRATICADO,
       CASE WHEN v.TP_VENDA = 'atacado' THEN f.VL_VENDA_ATACADO ELSE f.VL_VENDA_VAREJO END AS preco_de_tabela
FROM CONTEM c
JOIN VENDA v    ON v.ID_VENDA = c.ID_VENDA
JOIN FANTASIA f ON f.ID_FANTASIA = c.ID_FANTASIA
WHERE c.VL_PRATICADO <> CASE WHEN v.TP_VENDA = 'atacado' THEN f.VL_VENDA_ATACADO ELSE f.VL_VENDA_VAREJO END;

-- A03 — Existe entrega registrada em venda abaixo de R$ 200?
-- Verifica: RN02 (entrega só em compras a partir de R$ 200)
SELECT v.ID_VENDA, v.DT_VENDA, v.TP_ENTREGA, SUM(c.QT_ITEM * c.VL_PRATICADO) AS total
FROM VENDA v
JOIN CONTEM c ON c.ID_VENDA = v.ID_VENDA
WHERE v.TP_ENTREGA IS NOT NULL
GROUP BY v.ID_VENDA, v.DT_VENDA, v.TP_ENTREGA
HAVING SUM(c.QT_ITEM * c.VL_PRATICADO) < 200;

-- A04 — Existe troca de fantasia que não estava na venda original, ou com mais peças do que foram vendidas?
-- Verifica: RN04 (a troca se refere a uma fantasia comprada naquela venda)
SELECT t.ID_TROCA, t.DT_TROCA, t.ID_VENDA, t.ID_FANTASIA_DEVOLVIDA, t.QT_TROCA, c.QT_ITEM AS qt_vendida
FROM TROCA t
LEFT JOIN CONTEM c ON c.ID_VENDA = t.ID_VENDA AND c.ID_FANTASIA = t.ID_FANTASIA_DEVOLVIDA
WHERE c.ID_VENDA IS NULL OR t.QT_TROCA > c.QT_ITEM;

-- A05 — Existe cliente com telefone ou endereço guardado sem autorização LGPD?
-- Verifica: RN06 (dados pessoais só com autorização registrada)
SELECT ID_CLIENTE, NM_CLIENTE, NR_TELEFONE, DS_ENDERECO, IN_AUTORIZA_LGPD
FROM CLIENTE
WHERE IN_AUTORIZA_LGPD = 0 AND (NR_TELEFONE IS NOT NULL OR DS_ENDERECO IS NOT NULL);

-- A06 — Existe fantasia na quantidade mínima ou abaixo sem pedido de reposição nos 7 dias anteriores ao fim da massa?
-- Verifica: RN07 (reposição pedida ao fornecedor quando QT_DISPONIVEL chega a QT_MINIMA)
SELECT f.ID_FANTASIA, f.NM_FANTASIA, f.QT_DISPONIVEL, f.QT_MINIMA
FROM FANTASIA f
WHERE f.QT_DISPONIVEL <= f.QT_MINIMA
  AND NOT EXISTS (SELECT 1 FROM ENTRA en JOIN COMPRA co ON co.ID_COMPRA = en.ID_COMPRA
                  WHERE en.ID_FANTASIA = f.ID_FANTASIA
                    AND DATEDIFF((SELECT MAX(DT_VENDA) FROM VENDA), co.DT_PEDIDO) <= 7);

-- A07 — Existe item recebido com quantidade menor que a pedida e compra sem observação?
-- Verifica: RN09 (divergências são conferidas e anotadas)
SELECT co.ID_COMPRA, co.DT_COMPRA, fa.NM_FANTASIA, en.QT_SOLICITADA, en.QT_ENTRADA, co.DS_OBSERVACAO
FROM COMPRA co
JOIN ENTRA en    ON en.ID_COMPRA = co.ID_COMPRA
JOIN FANTASIA fa ON fa.ID_FANTASIA = en.ID_FANTASIA
WHERE en.QT_ENTRADA < en.QT_SOLICITADA AND (co.DS_OBSERVACAO IS NULL OR co.DS_OBSERVACAO = '');

-- A08 — Existe venda ou compra sem movimento de caixa, ou movimento com tipo incoerente com a origem?
-- Verifica: RN13 (todo movimento vem de uma venda ou de uma compra; venda é entrada e compra é saída)
SELECT 'venda sem movimento de caixa' AS problema, v.ID_VENDA AS codigo FROM VENDA v LEFT JOIN CAIXA cx ON cx.ID_VENDA = v.ID_VENDA WHERE cx.ID_MOV IS NULL
UNION ALL
SELECT 'compra sem movimento de caixa', co.ID_COMPRA FROM COMPRA co LEFT JOIN CAIXA cx ON cx.ID_COMPRA = co.ID_COMPRA WHERE cx.ID_MOV IS NULL
UNION ALL
SELECT 'movimento com tipo incoerente', ID_MOV FROM CAIXA
WHERE (ID_VENDA IS NOT NULL AND TP_MOV <> 'entrada') OR (ID_COMPRA IS NOT NULL AND TP_MOV <> 'saida');

-- A09 — Existe movimento de caixa com valor diferente do total da venda ou da compra de origem?
-- Verifica: RN13 (o caixa reflete exatamente o que foi vendido ou comprado)
SELECT cx.ID_MOV, cx.DT_MOV, cx.TP_MOV, cx.VL_MOV, cx.ID_VENDA, cx.ID_COMPRA,
       COALESCE(vt.total, ct.total) AS total_da_origem
FROM CAIXA cx
LEFT JOIN (SELECT ID_VENDA, SUM(QT_ITEM * VL_PRATICADO) AS total FROM CONTEM GROUP BY ID_VENDA) vt ON vt.ID_VENDA = cx.ID_VENDA
LEFT JOIN (SELECT ID_COMPRA, SUM(QT_ENTRADA * VL_CUSTO) AS total FROM ENTRA GROUP BY ID_COMPRA) ct ON ct.ID_COMPRA = cx.ID_COMPRA
WHERE ROUND(cx.VL_MOV - COALESCE(vt.total, ct.total), 2) <> 0;

-- A10 — Existe fechamento cuja diferença registrada não bate com (valor contado − valor esperado)?
-- Verifica: RN14 (diferença = valor contado menos o esperado pelos movimentos)
SELECT fc.ID_FECHAMENTO, fc.DT_FECHAMENTO, fc.VL_SALDO_INICIAL, COALESCE(m.liquido, 0) AS movimento_liquido,
       fc.VL_SALDO_INICIAL + COALESCE(m.liquido, 0) AS esperado, fc.VL_CONTADO, fc.VL_DIFERENCA,
       ROUND(fc.VL_CONTADO - (fc.VL_SALDO_INICIAL + COALESCE(m.liquido, 0)), 2) AS diferenca_correta
FROM FECHAMENTO_CAIXA fc
LEFT JOIN (SELECT ID_FECHAMENTO, SUM(CASE WHEN TP_MOV = 'entrada' THEN VL_MOV ELSE -VL_MOV END) AS liquido
           FROM CAIXA WHERE ID_FECHAMENTO IS NOT NULL GROUP BY ID_FECHAMENTO) m ON m.ID_FECHAMENTO = fc.ID_FECHAMENTO
WHERE ROUND(fc.VL_DIFERENCA - (fc.VL_CONTADO - (fc.VL_SALDO_INICIAL + COALESCE(m.liquido, 0))), 2) <> 0;

-- A11 — Existe fantasia cuja quantidade disponível difere de entradas − vendas ± trocas?
-- Verifica: RN07 / P4 (QT_DISPONIVEL é redundância controlada e precisa bater com o histórico)
SELECT * FROM (
  SELECT f.ID_FANTASIA, f.NM_FANTASIA, f.QT_DISPONIVEL AS registrado,
         COALESCE(e.qt, 0) - COALESCE(s.qt, 0) + COALESCE(td.qt, 0) - COALESCE(tn.qt, 0) AS calculado
  FROM FANTASIA f
  LEFT JOIN (SELECT ID_FANTASIA, SUM(QT_ENTRADA) AS qt FROM ENTRA GROUP BY ID_FANTASIA) e ON e.ID_FANTASIA = f.ID_FANTASIA
  LEFT JOIN (SELECT ID_FANTASIA, SUM(QT_ITEM) AS qt FROM CONTEM GROUP BY ID_FANTASIA) s ON s.ID_FANTASIA = f.ID_FANTASIA
  LEFT JOIN (SELECT ID_FANTASIA_DEVOLVIDA AS ID_FANTASIA, SUM(QT_TROCA) AS qt FROM TROCA GROUP BY ID_FANTASIA_DEVOLVIDA) td ON td.ID_FANTASIA = f.ID_FANTASIA
  LEFT JOIN (SELECT ID_FANTASIA_NOVA AS ID_FANTASIA, SUM(QT_TROCA) AS qt FROM TROCA GROUP BY ID_FANTASIA_NOVA) tn ON tn.ID_FANTASIA = f.ID_FANTASIA
) x
WHERE registrado <> calculado;

