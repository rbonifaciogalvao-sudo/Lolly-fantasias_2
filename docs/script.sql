CREATE TABLE CLIENTE (
  ID_CLIENTE        INT          NOT NULL AUTO_INCREMENT,
  NM_CLIENTE        VARCHAR(120) NOT NULL,
  NR_TELEFONE       VARCHAR(15)  NULL,
  DS_ENDERECO       VARCHAR(200) NULL,
  IN_AUTORIZA_LGPD  BOOLEAN      NOT NULL DEFAULT 0,   -- RN06
  CONSTRAINT pk_cliente PRIMARY KEY (ID_CLIENTE),
  CONSTRAINT ck_cliente_tel CHECK (NR_TELEFONE REGEXP '^[0-9]+$')
) ENGINE=InnoDB;

CREATE TABLE FUNCIONARIO (
  ID_FUNCIONARIO  INT          NOT NULL AUTO_INCREMENT,
  NM_FUNCIONARIO  VARCHAR(120) NOT NULL,
  DS_CARGO        VARCHAR(60)  NOT NULL,
  NR_TELEFONE     VARCHAR(15)  NULL,
  CONSTRAINT pk_funcionario PRIMARY KEY (ID_FUNCIONARIO),
  CONSTRAINT ck_func_tel CHECK (NR_TELEFONE REGEXP '^[0-9]+$')
) ENGINE=InnoDB;

CREATE TABLE FORNECEDOR (
  ID_FORNECEDOR  INT          NOT NULL AUTO_INCREMENT,
  NM_FORNECEDOR  VARCHAR(120) NOT NULL,
  NR_CNPJ        CHAR(14)     NOT NULL,
  NR_TELEFONE    VARCHAR(15)  NULL,
  CONSTRAINT pk_fornecedor PRIMARY KEY (ID_FORNECEDOR),
  CONSTRAINT uq_fornecedor_cnpj UNIQUE (NR_CNPJ),
  CONSTRAINT ck_forn_cnpj CHECK (NR_CNPJ REGEXP '^[0-9]{14}$'),
  CONSTRAINT ck_forn_tel CHECK (NR_TELEFONE REGEXP '^[0-9]+$')
) ENGINE=InnoDB;

CREATE TABLE FANTASIA (
  ID_FANTASIA       INT           NOT NULL AUTO_INCREMENT,
  NM_FANTASIA       VARCHAR(120)  NOT NULL,
  VL_VENDA_VAREJO   DECIMAL(10,2) NOT NULL,             -- RN10
  VL_VENDA_ATACADO  DECIMAL(10,2) NOT NULL,             -- RN01
  TP_TAMANHO        VARCHAR(20)   NOT NULL,
  TP_CATEGORIA      VARCHAR(40)   NOT NULL,             -- RN12
  TP_GENERO         VARCHAR(20)   NOT NULL,
  QT_DISPONIVEL     INT           NOT NULL DEFAULT 0,   -- RN07
  QT_MINIMA         INT           NOT NULL DEFAULT 5,   -- RN07
  ID_FORNECEDOR     INT           NOT NULL,             -- RN08
  CONSTRAINT pk_fantasia PRIMARY KEY (ID_FANTASIA),
  CONSTRAINT fk_fantasia_fornecedor FOREIGN KEY (ID_FORNECEDOR) REFERENCES FORNECEDOR (ID_FORNECEDOR),
  CONSTRAINT ck_fant_varejo CHECK (VL_VENDA_VAREJO > 0),
  CONSTRAINT ck_fant_atacado CHECK (VL_VENDA_ATACADO > 0 AND VL_VENDA_ATACADO <= VL_VENDA_VAREJO),
  CONSTRAINT ck_fant_disp CHECK (QT_DISPONIVEL >= 0),
  CONSTRAINT ck_fant_min CHECK (QT_MINIMA >= 0)
) ENGINE=InnoDB;

CREATE TABLE VENDA (
  ID_VENDA            INT          NOT NULL AUTO_INCREMENT,
  TP_VENDA            VARCHAR(10)  NOT NULL,                    -- RN01
  TP_FORMA_PAGAMENTO  VARCHAR(30)  NOT NULL,                    -- RN03
  DT_VENDA            DATE         NOT NULL DEFAULT (CURRENT_DATE),
  ID_CLIENTE          INT          NOT NULL,                    -- RN05
  ID_FUNCIONARIO      INT          NOT NULL,
  IN_ENCOMENDA        BOOLEAN      NOT NULL DEFAULT 0,          -- RN11
  TP_ENTREGA          VARCHAR(20)  NULL,                        -- RN02
  DT_ENTREGA          DATE         NULL,                        -- RN02
  CONSTRAINT pk_venda PRIMARY KEY (ID_VENDA),
  CONSTRAINT fk_venda_cliente FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTE (ID_CLIENTE),
  CONSTRAINT fk_venda_funcionario FOREIGN KEY (ID_FUNCIONARIO) REFERENCES FUNCIONARIO (ID_FUNCIONARIO),
  CONSTRAINT ck_venda_tipo CHECK (TP_VENDA IN ('varejo','atacado')),
  CONSTRAINT ck_venda_entrega_tp CHECK (TP_ENTREGA IN ('correio','excursao','onibus')),
  CONSTRAINT ck_venda_entrega_par CHECK ((TP_ENTREGA IS NULL AND DT_ENTREGA IS NULL) OR (TP_ENTREGA IS NOT NULL AND DT_ENTREGA IS NOT NULL)),
  CONSTRAINT ck_venda_entrega_dt CHECK (DT_ENTREGA >= DT_VENDA)
) ENGINE=InnoDB;

CREATE TABLE CONTEM (
  ID_VENDA      INT           NOT NULL,
  ID_FANTASIA   INT           NOT NULL,
  VL_PRATICADO  DECIMAL(10,2) NOT NULL,
  QT_ITEM       INT           NOT NULL,
  CONSTRAINT pk_contem PRIMARY KEY (ID_VENDA, ID_FANTASIA),
  CONSTRAINT fk_contem_venda FOREIGN KEY (ID_VENDA) REFERENCES VENDA (ID_VENDA),
  CONSTRAINT fk_contem_fantasia FOREIGN KEY (ID_FANTASIA) REFERENCES FANTASIA (ID_FANTASIA),
  CONSTRAINT ck_contem_valor CHECK (VL_PRATICADO > 0),
  CONSTRAINT ck_contem_qt CHECK (QT_ITEM > 0)
) ENGINE=InnoDB;

CREATE TABLE TROCA (
  ID_TROCA               INT          NOT NULL AUTO_INCREMENT,
  DT_TROCA               DATE         NOT NULL DEFAULT (CURRENT_DATE),
  DS_MOTIVO              VARCHAR(200) NOT NULL,
  QT_TROCA               INT          NOT NULL,
  ID_VENDA               INT          NOT NULL,
  ID_FANTASIA_DEVOLVIDA  INT          NOT NULL,             -- RN04
  ID_FANTASIA_NOVA       INT          NOT NULL,             -- RN04
  CONSTRAINT pk_troca PRIMARY KEY (ID_TROCA),
  CONSTRAINT fk_troca_venda FOREIGN KEY (ID_VENDA) REFERENCES VENDA (ID_VENDA),
  CONSTRAINT fk_troca_devolvida FOREIGN KEY (ID_FANTASIA_DEVOLVIDA) REFERENCES FANTASIA (ID_FANTASIA),
  CONSTRAINT fk_troca_nova FOREIGN KEY (ID_FANTASIA_NOVA) REFERENCES FANTASIA (ID_FANTASIA),
  CONSTRAINT ck_troca_qt CHECK (QT_TROCA > 0),
  CONSTRAINT ck_troca_diferentes CHECK (ID_FANTASIA_DEVOLVIDA <> ID_FANTASIA_NOVA)
) ENGINE=InnoDB;

CREATE TABLE COMPRA (
  ID_COMPRA       INT          NOT NULL AUTO_INCREMENT,
  DT_PEDIDO       DATE         NOT NULL,
  DT_COMPRA       DATE         NOT NULL DEFAULT (CURRENT_DATE),
  ID_FUNCIONARIO  INT          NOT NULL,
  DS_OBSERVACAO   VARCHAR(255) NULL,                        -- RN09
  CONSTRAINT pk_compra PRIMARY KEY (ID_COMPRA),
  CONSTRAINT fk_compra_funcionario FOREIGN KEY (ID_FUNCIONARIO) REFERENCES FUNCIONARIO (ID_FUNCIONARIO),
  CONSTRAINT ck_compra_datas CHECK (DT_COMPRA >= DT_PEDIDO)
) ENGINE=InnoDB;

CREATE TABLE ENTRA (
  ID_COMPRA      INT           NOT NULL,
  ID_FANTASIA    INT           NOT NULL,
  VL_CUSTO       DECIMAL(10,2) NOT NULL,                    -- RN10
  QT_SOLICITADA  INT           NOT NULL,
  QT_ENTRADA     INT           NOT NULL,                    -- RN09
  CONSTRAINT pk_entra PRIMARY KEY (ID_COMPRA, ID_FANTASIA),
  CONSTRAINT fk_entra_compra FOREIGN KEY (ID_COMPRA) REFERENCES COMPRA (ID_COMPRA),
  CONSTRAINT fk_entra_fantasia FOREIGN KEY (ID_FANTASIA) REFERENCES FANTASIA (ID_FANTASIA),
  CONSTRAINT ck_entra_custo CHECK (VL_CUSTO > 0),
  CONSTRAINT ck_entra_sol CHECK (QT_SOLICITADA > 0),
  CONSTRAINT ck_entra_ent CHECK (QT_ENTRADA >= 0)
) ENGINE=InnoDB;

CREATE TABLE FECHAMENTO_CAIXA (
  ID_FECHAMENTO     INT           NOT NULL AUTO_INCREMENT,
  VL_SALDO_INICIAL  DECIMAL(10,2) NOT NULL DEFAULT 0,
  DT_FECHAMENTO     DATE          NOT NULL DEFAULT (CURRENT_DATE),
  VL_CONTADO        DECIMAL(10,2) NOT NULL,
  VL_DIFERENCA      DECIMAL(10,2) NOT NULL,                 -- RN14 (pode ser negativo)
  CONSTRAINT pk_fechamento PRIMARY KEY (ID_FECHAMENTO),
  CONSTRAINT ck_fech_saldo CHECK (VL_SALDO_INICIAL >= 0),
  CONSTRAINT ck_fech_contado CHECK (VL_CONTADO >= 0)
) ENGINE=InnoDB;

CREATE TABLE CAIXA (
  ID_MOV         INT           NOT NULL AUTO_INCREMENT,
  ID_VENDA       INT           NULL,
  ID_COMPRA      INT           NULL,
  TP_MOV         VARCHAR(10)   NOT NULL,
  VL_MOV         DECIMAL(10,2) NOT NULL,
  DT_MOV         DATE          NOT NULL DEFAULT (CURRENT_DATE),
  DS_MOV         VARCHAR(200)  NULL,
  ID_FECHAMENTO  INT           NULL,                        -- RN14
  CONSTRAINT pk_caixa PRIMARY KEY (ID_MOV),
  CONSTRAINT fk_caixa_venda FOREIGN KEY (ID_VENDA) REFERENCES VENDA (ID_VENDA),
  CONSTRAINT fk_caixa_compra FOREIGN KEY (ID_COMPRA) REFERENCES COMPRA (ID_COMPRA),
  CONSTRAINT fk_caixa_fechamento FOREIGN KEY (ID_FECHAMENTO) REFERENCES FECHAMENTO_CAIXA (ID_FECHAMENTO),
  CONSTRAINT uq_caixa_venda UNIQUE (ID_VENDA),
  CONSTRAINT uq_caixa_compra UNIQUE (ID_COMPRA),
  CONSTRAINT ck_caixa_origem CHECK ((ID_VENDA IS NOT NULL AND ID_COMPRA IS NULL) OR (ID_VENDA IS NULL AND ID_COMPRA IS NOT NULL)),  -- RN13
  CONSTRAINT ck_caixa_tipo CHECK (TP_MOV IN ('entrada','saida')),
  CONSTRAINT ck_caixa_valor CHECK (VL_MOV > 0)
) ENGINE=InnoDB;

